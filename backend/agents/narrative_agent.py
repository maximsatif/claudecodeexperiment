"""Narrative Report Agent - Generates human-readable risk reports using LLM."""

import json
from datetime import datetime
from typing import Any

from strands import Agent, tool
from strands.models import BedrockModel

from backend.config import BEDROCK_MODEL_ID, AWS_REGION


@tool
def generate_risk_briefing(
    systemic_risk_score: float,
    critical_nodes: str,
    anomalies: str,
    sentiment_summary: str,
    margin_status: str,
) -> str:
    """Generate a comprehensive risk briefing from multiple data sources.

    This tool synthesizes inputs from other agents into a coherent narrative.

    Args:
        systemic_risk_score: Overall systemic risk score (0-100).
        critical_nodes: JSON string of critical nodes from the contagion graph.
        anomalies: JSON string of detected anomalies.
        sentiment_summary: JSON string of news sentiment analysis.
        margin_status: JSON string of margin risk assessment.
    """
    # This tool is a placeholder - the actual narrative is generated by the agent's LLM
    return json.dumps({
        "inputs_received": {
            "systemic_risk_score": systemic_risk_score,
            "critical_nodes": critical_nodes[:200],
            "anomalies": anomalies[:200],
            "sentiment": sentiment_summary[:200],
            "margin": margin_status[:200],
        },
        "timestamp": datetime.now().isoformat(),
    })


@tool
def format_executive_summary(
    risk_level: str,
    key_findings: str,
    recommended_actions: str,
) -> str:
    """Format findings into an executive summary for senior leadership.

    Args:
        risk_level: Overall risk level (low, moderate, elevated, high, critical).
        key_findings: JSON array of key findings.
        recommended_actions: JSON array of recommended actions.
    """
    return json.dumps({
        "risk_level": risk_level,
        "key_findings": key_findings,
        "recommended_actions": recommended_actions,
        "generated_at": datetime.now().isoformat(),
    })


def create_narrative_agent() -> Agent:
    """Create and return the Narrative Report Agent."""
    model = BedrockModel(
        model_id=BEDROCK_MODEL_ID,
        region_name=AWS_REGION,
        temperature=0.3,  # Slightly more creative for narrative generation
    )

    agent = Agent(
        model=model,
        tools=[
            generate_risk_briefing,
            format_executive_summary,
        ],
        system_prompt="""You are a Financial Risk Narrative Agent. Your role is to synthesize complex
quantitative risk data into clear, actionable narratives for risk managers and senior leadership.

When generating risk briefings, follow this structure:

1. **Risk Level Assessment**: Start with the overall risk classification (Low/Moderate/Elevated/High/Critical)
   and the systemic risk score.

2. **Key Findings**: List 3-5 most important findings, prioritized by severity:
   - Market anomalies detected (price, volume, correlation breakdowns)
   - Contagion pathways identified (which entities, how risk propagates)
   - News/sentiment signals (negative headlines, regulatory actions)
   - Margin risk status (utilization, margin call probability)

3. **Contagion Pathways**: Describe the most likely paths of risk propagation:
   - Source entity → transmission mechanism → affected entities
   - Use the R0 number to explain whether contagion would spread or die out

4. **Margin Impact**: Quantify the potential financial impact:
   - Portfolio losses under stress scenarios
   - Margin call probabilities and timing
   - Cascading margin effects on counterparties

5. **Recommended Actions**: Provide specific, prioritized actions:
   - Immediate (within hours): Emergency hedges, position reductions
   - Short-term (within days): Margin adjustments, collateral optimization
   - Medium-term (within weeks): Portfolio restructuring, counterparty limit reviews

Write in a professional, concise tone suitable for a risk committee briefing.
Use specific numbers, percentages, and entity names. Avoid vague language.
Format the output as structured JSON with clear sections.""",
    )
    return agent
